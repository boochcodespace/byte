// Browser: alt text editors, drafting, and what the lesson page shows
// Run by `npm run test:a11y`. Uses a mock AI model and a throwaway HOME.
const h = require('./support/ui-harness')
const { APP, L, MOCK, P, api, check, draftViaApi, launchBrowser, proposal, setMode, startEnv, stopEnv, waitFor } = h
const { AxeBuilder } = require('@axe-core/playwright')
async function main() {
  await h.startEnv({ ui: true })
  await api('GET', '/projects')
  await api('POST', '/settings', { provider: 'local', model: 'm', baseUrl: `${MOCK}/v1` })
  const browser = await h.launchBrowser()
  const ctx = await browser.newContext({ viewport: { width: 1200, height: 1500 } })
  const page = await ctx.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(String(e)))
  page.on('console', m => { if (m.type() === 'error' && !/^Failed to load resource/.test(m.text())) errors.push(m.text()) })
  const lessonOf = async id => (await api('GET', `${L}/${id}`)).data.lesson
  // axe violations that fall inside the new text-alternative UI
  const axeInNew = async () => {
    const r = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze()
    return r.violations.filter(v => v.id !== 'color-contrast').flatMap(v => v.nodes.filter(n => n.target.join(' ').match(/visual-alt|lesson-visual|grow-textarea/) || /visual-alt|lesson-visual/.test(n.html)).map(n => v.id + ' ' + n.target.join(' ')))
  }

  try {
    const id = await draftViaApi({}, { withTabs: true })
    await page.goto(`${APP}/projects/${P}/lessons/${id}`)
    await page.waitForSelector('.lesson-block-hook')
    const chunk = page.locator('.lesson-block-chunk').first()

    console.log('Display: what the lesson page shows')
    check('a chunk shows its alt text as the visual, not the brief', await chunk.locator('.lesson-visual p', { hasText: 'ALT VISUAL' }).isVisible())
    check('the brief is labelled author-only', await chunk.locator('text=Brief for the author (not shown to learners): VISUAL-2').isVisible())
    check('no disclosure button when there is no long description', !(await chunk.locator('button:has-text("Describe this visual")').count()))

    console.log('Editor: text alternative fields')
    await chunk.locator('button:has-text("Edit")').click()
    const alt = chunk.getByLabel('Alt text')
    check('alt text is prefilled and labelled', (await alt.inputValue()).startsWith('ALT'))
    check('a live counter reads "N of 125 characters"', await chunk.locator('text=/\\d+ of 125 characters/').isVisible())
    check('the alt field is described by the counter (aria-describedby)', !!(await alt.getAttribute('aria-describedby')))
    await alt.fill('x'.repeat(130))
    check('past 125: a soft warning appears (role=status)', await chunk.locator('[role=status]:has-text("130 characters. 125 or fewer reads best. You can still save it.")').isVisible())
    await chunk.locator('button:has-text("Save")').click()
    await page.waitForFunction(() => document.body.textContent.includes('xxxxxxxxxx'))
    check('130 characters SAVES (soft limit, never blocks)', (await lessonOf(id)).blocks.find(b => b.kind === 'chunk').alt_text.length === 130)

    await chunk.locator('button:has-text("Edit")').click()
    await chunk.getByLabel(/Visual note/).fill('A diagram of the host, client and server roles.')
    check('a long-description field is offered, marked optional', await chunk.getByLabel(/Long description/).isVisible())
    const before = JSON.stringify((await lessonOf(id)).blocks.find(b => b.kind === 'chunk'))
    await chunk.locator('button:has-text("Generate alt text")').click()
    check('the button shows it is working', await chunk.locator('button:has-text("Drafting...")').isVisible())
    await chunk.locator('text=Draft from Byte. Review and edit it, then save. It is not saved yet.').waitFor()
    check('the draft fills alt text', (await chunk.getByLabel('Alt text').inputValue()).startsWith('DRAFT-ALT A diagram'))
    check('...and, for a diagram, the long description', /DRAFT-LONG/.test(await chunk.getByLabel(/Long description/).inputValue()))
    check('the draft is announced as not saved (role=status)', await chunk.locator('[role=status]:has-text("not saved yet")').isVisible())
    check('NOTHING is saved by drafting', JSON.stringify((await lessonOf(id)).blocks.find(b => b.kind === 'chunk')) === before)
    check('axe: no violations inside the new fields while editing', (await axeInNew()).length === 0, await axeInNew())
    await chunk.locator('button:has-text("Cancel")').click()
    check('Cancel throws the draft away', JSON.stringify((await lessonOf(id)).blocks.find(b => b.kind === 'chunk')) === before)

    await chunk.locator('button:has-text("Edit")').click()
    await chunk.getByLabel(/Visual note/).fill('A diagram of the host, client and server roles.')
    await chunk.locator('button:has-text("Generate alt text")').click()
    await chunk.locator('text=Draft from Byte').waitFor()
    await chunk.locator('button:has-text("Save")').click()
    await page.waitForSelector('.lesson-block-chunk >> text=DRAFT-ALT')
    const saved = (await lessonOf(id)).blocks.find(b => b.kind === 'chunk')
    check('saving the draft stores alt_text and long_description', /^DRAFT-ALT/.test(saved.alt_text) && /DRAFT-LONG/.test(saved.long_description) && saved.edited === true)

    console.log('Display: Describe this visual')
    const disc = chunk.locator('button:has-text("Describe this visual")')
    check('a disclosure button appears under the alt text', await disc.isVisible() && (await disc.getAttribute('aria-expanded')) === 'false')
    const region = chunk.locator(`[id="${await disc.getAttribute('aria-controls')}"]`)
    check('the long description is hidden until asked', !(await region.isVisible()))
    await disc.focus(); await page.keyboard.press('Enter')
    check('Enter opens it; aria-expanded is true; the text shows', (await disc.getAttribute('aria-expanded')) === 'true' && await region.isVisible() && /DRAFT-LONG/.test(await region.textContent()))
    await page.keyboard.press('Space')
    check('Space closes it again', (await disc.getAttribute('aria-expanded')) === 'false' && !(await region.isVisible()))
    check('axe: no violations in the visual display', (await axeInNew()).length === 0, await axeInNew())

    console.log('Decorative')
    await chunk.locator('button:has-text("Edit")').click()
    const dec = chunk.getByLabel(/This visual is decorative/)
    await dec.focus(); await page.keyboard.press('Space')
    check('the checkbox works by keyboard and hides the alt fields', await dec.isChecked() && !(await chunk.getByLabel('Alt text').count()))
    check('a reason field appears', await chunk.getByLabel('Why is it decorative?').isVisible())
    await chunk.getByLabel('Why is it decorative?').fill('Spacer only')
    await chunk.locator('button:has-text("Save")').click()
    await page.waitForSelector('.lesson-block-chunk >> text=Decorative visual')
    check('a decorative visual is described to the author as left out for screen readers', await chunk.locator('text=/Decorative visual, left out for screen readers: Spacer only/').isVisible())
    check('...and has no Visual box for learners', !(await chunk.locator('.lesson-visual').count()))

    console.log('Legacy and failure')
    await api('PUT', `${L}/${id}/blocks/${(await lessonOf(id)).blocks.filter(b => b.kind === 'chunk')[1].id}/text`, { title: 'Legacy', body: 'Body', visual: 'OLD BRIEF only' })
    await page.reload(); await page.waitForSelector('.lesson-block-hook')
    const legacy = page.locator('.lesson-block-chunk').nth(1)
    check('a chunk with a visual and no alt text shows the brief and a "No alt text yet" note', await legacy.locator('text=OLD BRIEF only').isVisible() && await legacy.locator('text=No alt text yet').isVisible())
    await legacy.locator('button:has-text("Edit")').click()
    setMode('notjson')
    await legacy.locator('button:has-text("Generate alt text")').click()
    await legacy.locator('[role=alert]').waitFor()
    setMode('ok')
    check('a failed draft says so in a role=alert message and changes no field', /could not|failed|try again/i.test(await legacy.locator('[role=alert]').textContent()) && (await legacy.getByLabel('Alt text').inputValue()) === '')
    await legacy.getByLabel('Alt text').fill('Written myself.')
    await legacy.locator('button:has-text("Save")').click()
    await page.waitForSelector('.lesson-block-chunk >> text=Written myself.')
    check('writing alt text by hand works without any AI', (await lessonOf(id)).blocks.filter(b => b.kind === 'chunk')[1].alt_text === 'Written myself.')

    console.log('Tabs')
    const tabsB = page.locator('.lesson-proposal:has-text("Tabs"), .lesson-tabs-block').first()
    if (await tabsB.locator('button:has-text("Write it myself")').count()) await tabsB.locator('button:has-text("Write it myself")').click()
    const ed = tabsB.locator('.tabs-editor')
    await ed.getByLabel('Tab 1 label').fill('Host'); await ed.getByLabel('Tab 1 text').fill('Host body.')
    await ed.getByLabel('Tab 2 label').fill('Client'); await ed.getByLabel('Tab 2 text').fill('Client body.')
    check('no alt fields until a visual note exists', !(await ed.getByLabel('Tab 1 alt text').count()))
    await ed.getByLabel('Tab 1 visual note').fill('A comparison table of host and client.')
    check('Tab 1 gets its own alt text, long description, and decorative checkbox', await ed.getByLabel('Tab 1 alt text').isVisible() && await ed.getByLabel('Tab 1 long description').isVisible() && await ed.getByLabel(/Tab 1: This visual is decorative/).isVisible())
    check('Tab 2 has none yet', !(await ed.getByLabel('Tab 2 alt text').count()))
    await ed.locator('button:has-text("Generate tab 1 alt text")').click()
    await ed.locator('text=Draft from Byte').first().waitFor()
    check('the per-tab draft fills Tab 1 only', /DRAFT-ALT A comparison/.test(await ed.getByLabel('Tab 1 alt text').inputValue()) && /DRAFT-LONG/.test(await ed.getByLabel('Tab 1 long description').inputValue()))
    await ed.locator('button[type=submit]').click()
    await page.waitForSelector('.lesson-tabs')
    const tb = (await lessonOf(id)).blocks.find(b => b.kind === 'tabs')
    check('saved with alt text on tab 1 only', /DRAFT-ALT/.test(tb.tabs[0].alt_text) && tb.tabs[1].alt_text === undefined)
    const tdisc = page.locator('.lesson-tabs button:has-text("Describe this visual")')
    check('the tab view shows alt text and a Describe this visual disclosure', await page.locator('.lesson-tabpanel:visible .lesson-visual p', { hasText: 'DRAFT-ALT' }).isVisible() && await tdisc.isVisible())
    check('axe: no violations in the tabs visual', (await axeInNew()).length === 0, await axeInNew())

    check('no page errors', errors.length === 0, errors)
  } finally {
    await browser.close(); await h.stopEnv()
  }
  h.finish()
}
main().catch(e => { console.error(e); process.exit(1) })
