// API: the accessibility checker, reviews, and the export gate
// Run by `npm run test:a11y`. Uses a mock AI model and a throwaway HOME.
const h = require('./support/api-harness')
const { HOME, KC, L, MOCK, P, PRIMARY, api, check, fs, http, newApprovedLesson, path, setMode, sleep, startEnv, stopEnv, REPO } = h
async function main() {
  await h.startEnv({ ui: false })
  try {
    await api('GET', '/projects')
    await api('POST', '/settings', { provider: 'local', model: 'm', baseUrl: `${MOCK}/v1` })
    const lessonOf = async id => (await api('GET', `${L}/${id}`)).data.lesson
    const lessonFile = id => path.join(HOME, 'Byte', 'projects', P, 'lessons', id, 'lesson.json')
    const onDisk = id => JSON.parse(fs.readFileSync(lessonFile(id), 'utf-8'))
    const draft = async (m = 'ok') => { const id = await newApprovedLesson(); setMode(m); await api('POST', `${L}/${id}/text/generate`); setMode('ok'); return id }
    const rep = async id => (await api('GET', `${L}/${id}/a11y`))
    const rules = r => r.data.issues.map(i => i.rule)
    // reading level and acronyms are advisory notes; the checks below count the rest
    const ADVISORY = ['reading-level', 'acronym-not-spelled-out']
    const real = r => r.data.issues.filter(i => !ADVISORY.includes(i.rule))
    const find = (r, rule) => r.data.issues.filter(i => i.rule === rule)
    const edit = (id, b, body) => api('PUT', `${L}/${id}/blocks/${b}/text`, body)

    console.log('Baseline')
    let id = await draft()
    let les = await lessonOf(id)
    let r = await rep(id)
    check('a fresh lesson has no content problems (advisory notes aside)', r.ok && real(r).filter(i => i.category === 'content').length === 0, real(r))
    check('its three suggestions are listed as blocks learners will not see', find(r, 'preview-skipped-proposal').length === 3 && find(r, 'preview-skipped-proposal').every(i => i.category === 'preview' && i.severity === 'note' && i.fix === 'resolve' && i.blockId))
    check('summary: no errors or warnings; the three suggestions are notes (plus any advisory notes)', r.data.summary.errors === 0 && r.data.summary.warnings === 0 && r.data.summary.notes === 3 + r.data.issues.filter(i => ADVISORY.includes(i.rule)).length && r.data.summary.reviewed === 0, r.data.summary)
    check('not drafted → validation', (await api('GET', `${L}/${await newApprovedLesson()}/a11y`)).errorType === 'validation')
    check('unknown lesson → not_found; unsafe id → not_found', (await api('GET', `${L}/nope/a11y`)).errorType === 'not_found' && (await api('GET', `${L}/a..b/a11y`)).errorType === 'not_found')

    console.log('Visuals')
    const ch = les.blocks.filter(b => b.kind === 'chunk')
    await edit(id, ch[0].id, { title: ch[0].title, body: ch[0].body, visual: 'A diagram with no alt text' })
    r = await rep(id)
    let miss = find(r, 'missing-alt-text')
    check('a visual with no alt text is an ERROR with the block and a Fix', miss.length === 1 && miss[0].severity === 'error' && miss[0].blockId === ch[0].id && miss[0].fix === 'edit' && /^chunk: /.test(miss[0].where), miss)
    check('...and the preview-skipped visual is listed too', find(r, 'preview-skipped-visual').length === 1)
    check('messages are plain language', /learners will not see it/.test(miss[0].message))
    await edit(id, ch[0].id, { title: ch[0].title, body: ch[0].body, visual: 'v', decorative: true })
    r = await rep(id)
    check('decorative with no reason → warning', find(r, 'decorative-no-reason').length === 1 && find(r, 'missing-alt-text').length === 0)
    await edit(id, ch[0].id, { title: ch[0].title, body: ch[0].body, visual: 'v', decorative: true, decorative_reason: 'Spacer' })
    r = await rep(id)
    check('decorative with a reason → clean', find(r, 'decorative-no-reason').length === 0 && find(r, 'missing-alt-text').length === 0 && find(r, 'preview-skipped-visual').length === 0)
    await edit(id, ch[0].id, { title: ch[0].title, body: ch[0].body, visual: 'v', alt_text: 'x'.repeat(126) })
    r = await rep(id)
    check('alt text of 126 characters → a note (soft guide)', find(r, 'alt-text-long').length === 1 && find(r, 'alt-text-long')[0].severity === 'note')
    await edit(id, ch[0].id, { title: ch[0].title, body: ch[0].body, visual: 'v', alt_text: 'x'.repeat(125) })
    check('125 characters → clean', find(await rep(id), 'alt-text-long').length === 0)
    // tabs
    const idT = await draft('text_with_tabs')
    const lt = await lessonOf(idT); const tabsB = lt.blocks.find(b => b.kind === 'tabs')
    await api('PUT', `${L}/${idT}/blocks/${tabsB.id}/tabs`, { title: 'Roles', tabs: [{ label: 'Host', body: 'h', visual: 'brief only' }, { label: 'Client', body: 'c', visual: 'v2', alt_text: 'ok alt' }] })
    r = await rep(idT)
    miss = find(r, 'missing-alt-text')
    check('a tab visual with no alt text is an error that names the tab', miss.length === 1 && /tab "Host"/.test(miss[0].where) && miss[0].fix === 'edit' && miss[0].blockId === tabsB.id, miss)
    check('the tab with alt text is fine', miss.every(i => !/Client/.test(i.where)))
    const proposalTabs = (await draft('text_with_tabs'))
    check('a proposed tabs block is listed as skipped', find(await rep(proposalTabs), 'preview-skipped-proposal').some(i => /tabs block/.test(i.where) && /tabs block has nothing/.test(i.message)))

    console.log('Flip decks used in the lesson')
    const GEN = `/projects/${P}/sources/${PRIMARY}/artifacts/generate`
    const gen = await api('POST', GEN, { artifactType: 'flip-card-deck' })
    const goodDeck = (await api('GET', `/projects/${P}/artifacts?type=flip-card-deck`)).data[0]
    const artDir = f => path.join(HOME, 'Byte', 'projects', P, 'sources', PRIMARY, 'artifacts', f)
    const accept = async (lid, type, a) => { const b = (await lessonOf(lid)).blocks.find(x => x.artifact_type === type && x.state === 'proposed'); return api('POST', `${L}/${lid}/blocks/${b.id}/artifact`, { mode: 'existing', source: a.source, artifact: a.folder }) }
    await accept(id, 'flip-card-deck', goodDeck)
    check('a deck with alt text is fine', find(await rep(id), 'deck-missing-alt-text').length === 0)
    // an older deck: visual described, no alt text
    await sleep(5)
    await api('POST', GEN, { artifactType: 'flip-card-deck' })
    const decks = (await api('GET', `/projects/${P}/artifacts?type=flip-card-deck`)).data
    const oldDeck = decks.find(d => d.folder !== goodDeck.folder)
    const aj = JSON.parse(fs.readFileSync(path.join(artDir(oldDeck.folder), 'artifact.json'), 'utf-8')); delete aj.alt_text
    fs.writeFileSync(path.join(artDir(oldDeck.folder), 'artifact.json'), JSON.stringify(aj))
    const idD = await draft(); await accept(idD, 'flip-card-deck', oldDeck)
    r = await rep(idD)
    const dm = find(r, 'deck-missing-alt-text')
    check('a deck with a visual but no alt text is flagged (warning, fix = regenerate)', dm.length === 1 && dm[0].severity === 'warning' && dm[0].fix === 'regenerate' && /flip card deck/.test(dm[0].where), dm)
    check('the deck is still not rendered or changed', JSON.parse(fs.readFileSync(path.join(artDir(oldDeck.folder), 'artifact.json'), 'utf-8')).alt_text === undefined)

    console.log('Headings')
    const idH = await draft()
    const lh = await lessonOf(idH); const hc = lh.blocks.filter(b => b.kind === 'chunk')
    await edit(idH, hc[0].id, { title: 'A', body: hc[0].body, visual: hc[0].visual, alt_text: 'alt' })
    check('a one-letter chunk title → error "missing heading"', find(await rep(idH), 'missing-heading').some(i => i.blockId === hc[0].id && i.severity === 'error'))
    await edit(idH, hc[0].id, { title: 'First do this. Then do that next.', body: hc[0].body, visual: hc[0].visual, alt_text: 'alt' })
    check('a two-sentence title → warning "reads like text"', find(await rep(idH), 'heading-reads-like-text').length === 1)
    await edit(idH, hc[0].id, { title: 'T'.repeat(100), body: hc[0].body, visual: hc[0].visual, alt_text: 'alt' })
    check('a 100-character title → warning', find(await rep(idH), 'heading-reads-like-text').length === 1)
    await edit(idH, hc[0].id, { title: 'What is changeover?', body: hc[0].body, visual: hc[0].visual, alt_text: 'alt' })
    check('a normal title is clean', find(await rep(idH), 'heading-reads-like-text').length === 0 && find(await rep(idH), 'missing-heading').length === 0)
    for (const b of hc) await api('DELETE', `${L}/${idH}/blocks/${b.id}`)
    r = await rep(idH)
    check('a lesson with no headings at all → a lesson-level warning (no block, no Fix)', find(r, 'missing-heading').some(i => i.blockId === null && i.fix === 'none' && i.severity === 'warning'))

    console.log('Color, position, shape, links')
    const idC = await draft()
    const lc = await lessonOf(idC)
    const hook = lc.blocks.find(b => b.kind === 'hook'), apply = lc.blocks.find(b => b.kind === 'apply'), rc = lc.blocks.find(b => b.kind === 'recall')
    await edit(idC, hook.id, { body: 'Press the green button on the left to start.' })
    r = await rep(idC)
    const co = find(r, 'color-only-reference')
    check('"the green button" and "button on the left" are both flagged for the hook', co.length === 2 && co.every(i => i.blockId === hook.id && i.fix === 'edit' && i.severity === 'warning'), co.map(i => i.message))
    check('the message quotes the phrase and says what to do instead', co.some(i => /"the green button"/.test(i.message) && /label or what they do/.test(i.message)))
    for (const [text, expect] of [['Look at the top option.', 1], ['Choose the round icon.', 1], ['It is shown in red.', 1], ['The right answer is to ask.', 0], ['Use the green light method.', 0], ['Open the box in the left-hand column.', 1]]) {
      await edit(idC, apply.id, { body: text })
      check(`"${text}" → ${expect} issue(s)`, find(await rep(idC), 'color-only-reference').filter(i => i.blockId === apply.id).length === expect)
    }
    await edit(idC, apply.id, { body: 'Click here to read more.' })
    check('"click here" and "read more" → vague link text (2)', find(await rep(idC), 'vague-link-text').filter(i => i.blockId === apply.id).length === 2)
    await edit(idC, apply.id, { body: 'See [here](http://example.com) and [](http://example.com).' })
    r = await rep(idC)
    check('markdown links: [here](…) is vague, [](…) is an ERROR (empty link text)', find(r, 'vague-link-text').filter(i => i.blockId === apply.id).length === 1 && find(r, 'empty-link-text').some(i => i.blockId === apply.id && i.severity === 'error'))
    await edit(idC, rc.id, { body: 'Which is the blue box?', answer: 'The one on the right side of the page.' })
    check('recall questions and answers are scanned', find(await rep(idC), 'color-only-reference').filter(i => i.blockId === rc.id).length >= 1)
    await edit(idC, apply.id, { body: 'Next time you build a schedule, list the changeover minutes first.' })
    check('clean wording clears the issues', find(await rep(idC), 'vague-link-text').length === 0 && find(await rep(idC), 'empty-link-text').length === 0)
    // tabs text
    const tc = await lessonOf(idT)
    await api('PUT', `${L}/${idT}/blocks/${tabsB.id}/tabs`, { title: 'Roles', tabs: [{ label: 'Host', body: 'The red option is the host.' }, { label: 'Client', body: 'c' }] })
    check('tab text is scanned', find(await rep(idT), 'color-only-reference').some(i => i.blockId === tabsB.id && /tab "Host" text/.test(i.message)))
    // artifacts: KC feedback and scenario text
    await api('POST', GEN, { artifactType: 'knowledge-check' }); await sleep(5); await api('POST', GEN, { artifactType: 'scenario-branching' })
    const kcA = (await api('GET', `/projects/${P}/artifacts?type=knowledge-check`)).data[0], scA = (await api('GET', `/projects/${P}/artifacts?type=scenario-branching`)).data[0]
    const kj = JSON.parse(fs.readFileSync(path.join(artDir(kcA.folder), 'artifact.json'), 'utf-8')); kj.items[0].options[1].rationale = 'Pick the green option instead.'; fs.writeFileSync(path.join(artDir(kcA.folder), 'artifact.json'), JSON.stringify(kj))
    const sj = JSON.parse(fs.readFileSync(path.join(artDir(scA.folder), 'artifact.json'), 'utf-8')); sj.nodes[0].choices[0].feedback = 'Press the button on the left next time.'; fs.writeFileSync(path.join(artDir(scA.folder), 'artifact.json'), JSON.stringify(sj))
    const idA = await draft(); await accept(idA, 'knowledge-check', kcA); await accept(idA, 'scenario-branching', scA)
    r = await rep(idA)
    const ai = find(r, 'color-only-reference')
    check('knowledge check feedback is scanned (fix = regenerate)', ai.some(i => /knowledge check/.test(i.where) && /feedback/.test(i.message) && i.fix === 'regenerate'), ai.map(i => i.where + i.message))
    check('scenario feedback is scanned', ai.some(i => /scenario/.test(i.where) && /feedback/.test(i.message)))

    console.log('Blocks the learner preview will skip')
    const idS = await draft()
    const sp = (await lessonOf(idS)).blocks.find(b => b.artifact_type === 'knowledge-check')
    await accept(idS, 'knowledge-check', kcA)
    fs.rmSync(artDir(kcA.folder), { recursive: true, force: true })
    r = await rep(idS)
    const mi = find(r, 'preview-skipped-missing-artifact')
    check('an artifact that is gone → warning, "no longer available", fix = resolve', mi.length === 1 && mi[0].severity === 'warning' && mi[0].category === 'preview' && mi[0].fix === 'resolve' && /no longer available/.test(mi[0].message) && mi[0].blockId === sp.id, mi)
    check('the other two proposals are listed', find(r, 'preview-skipped-proposal').length === 2)

    console.log('Reviews')
    const idR = await draft()
    const lr = await lessonOf(idR); const rch = lr.blocks.filter(b => b.kind === 'chunk')
    await edit(idR, rch[0].id, { title: rch[0].title, body: rch[0].body, visual: 'v' })
    r = await rep(idR)
    const target = find(r, 'missing-alt-text')[0]
    const rev = body => api('PUT', `${L}/${idR}/a11y/reviews`, body)
    check('a reason is required to mark reviewed', (await rev({ key: target.key })).errorType === 'validation' && (await rev({ key: target.key, reason: '   ' })).errorType === 'validation')
    check('an unknown key → not_found', (await rev({ key: 'nope', reason: 'x' })).errorType === 'not_found')
    r = await rev({ key: target.key, reason: 'Decoration added by the design team later' })
    const t2 = r.data.issues.find(i => i.key === target.key)
    check('reviewed: the issue is marked with its reason, counts move from open to reviewed', t2.reviewed === true && t2.review_reason === 'Decoration added by the design team later' && r.data.summary.errors === 0 && r.data.summary.reviewed === 1, r.data.summary)
    check('the review is saved in the lesson file', onDisk(idR).a11y_reviews.length === 1 && onDisk(idR).a11y_reviews[0].reason.startsWith('Decoration'))
    check('a fresh report keeps it reviewed', (await rep(idR)).data.issues.find(i => i.key === target.key).reviewed === true)
    await edit(idR, rch[0].id, { title: rch[0].title, body: rch[0].body, visual: 'a different visual brief' })
    r = await rep(idR)
    check('EDITING the visual brings the issue back (the review is tied to the text)', find(r, 'missing-alt-text')[0].reviewed === false && r.data.summary.errors === 1)
    check('...and the stale review is dropped on the next save', (await rev({ key: find(r, 'missing-alt-text')[0].key, reason: 'ok again' })).ok && onDisk(idR).a11y_reviews.length === 1)
    r = await rev({ key: find(await rep(idR), 'missing-alt-text')[0].key, reason: '' })
    check('an empty reason undoes a review', r.ok && find(r, 'missing-alt-text')[0].reviewed === false && onDisk(idR).a11y_reviews.length === 0)
    check('reviewing is allowed for warnings and notes too', (await rev({ key: find(await rep(idR), 'preview-skipped-proposal')[0].key, reason: 'We will add it later' })).ok)

    console.log('Advisory checks: reading level and acronyms (notes only)')
    const idV = await draft()
    const lv = await lessonOf(idV)
    const vh = lv.blocks.find(b => b.kind === 'hook'), va = lv.blocks.find(b => b.kind === 'apply'), vc = lv.blocks.filter(b => b.kind === 'chunk')
    const HARD = 'Notwithstanding the aforementioned considerations regarding organizational infrastructure, administrators should systematically evaluate configuration inconsistencies throughout heterogeneous environments before implementing remediation procedures, because unanticipated interdependencies frequently necessitate comprehensive reevaluation.'
    const EASY = 'You can do this. Open the plan. Check the time it takes to switch jobs. Write it down. Then pick the order that wastes the least time. Tell your team why you chose it.'
    await edit(idV, vh.id, { body: HARD })
    r = await rep(idV)
    let rl = find(r, 'reading-level').filter(i => i.blockId === vh.id)
    check('hard text → a reading-level NOTE with the grade, a rough-estimate caveat, and a Fix', rl.length === 1 && rl[0].severity === 'note' && /about grade \d+/.test(rl[0].message) && /rough estimate/.test(rl[0].message) && rl[0].fix === 'edit', rl)
    await edit(idV, vh.id, { body: EASY })
    check('plain short sentences → no reading-level note', find(await rep(idV), 'reading-level').filter(i => i.blockId === vh.id).length === 0)
    await edit(idV, vh.id, { body: 'Notwithstanding the aforementioned considerations.' })
    check('text under 25 words is not graded (too short to estimate)', find(await rep(idV), 'reading-level').filter(i => i.blockId === vh.id).length === 0)
    await edit(idV, vh.id, { body: HARD })
    const key = find(await rep(idV), 'reading-level').find(i => i.blockId === vh.id).key
    r = await api('PUT', `${L}/${idV}/a11y/reviews`, { key, reason: 'Legal wording that must stay exact' })
    check('a reading-level note can be reviewed with a reason', r.ok && r.data.issues.find(i => i.key === key).reviewed === true)
    await edit(idV, vh.id, { body: 'Use ' + EASY })
    await api('PUT', `${L}/${idT}/blocks/${tabsB.id}/tabs`, { title: 'Roles', tabs: [{ label: 'Host', body: HARD }, { label: 'Client', body: 'c' }] })
    check('hard tab text → a reading-level note on the tabs block', find(await rep(idT), 'reading-level').some(i => i.blockId === tabsB.id))

    await edit(idV, vh.id, { body: 'You will use the DNS to look up a name.' })
    r = await rep(idV)
    let ac = find(r, 'acronym-not-spelled-out')
    check('an unexplained acronym → a NOTE at its first appearance, naming it', ac.some(i => i.detail === 'DNS' && i.blockId === vh.id && i.severity === 'note' && /Domain Name System \(DNS\)/.test(i.message)), ac.map(i => i.detail))
    await edit(idV, va.id, { body: 'Next time, ask the DNS again.' })
    check('a second use of the same acronym later is not flagged again', find(await rep(idV), 'acronym-not-spelled-out').filter(i => i.detail === 'DNS').length === 1)
    await edit(idV, vh.id, { body: 'You will use the Domain Name System (DNS) to look up a name.' })
    check('"Full Name (ACR)" at the first use → clean', find(await rep(idV), 'acronym-not-spelled-out').filter(i => i.detail === 'DNS').length === 0)
    await edit(idV, vh.id, { body: 'You will use DNS (Domain Name System) to look up a name.' })
    check('"ACR (Full Name)" at the first use → clean', find(await rep(idV), 'acronym-not-spelled-out').filter(i => i.detail === 'DNS').length === 0)
    await edit(idV, vh.id, { body: 'It is OK to ask. NOT knowing is fine. You need an ID at 9 AM.' })
    check('everyday capitals (OK, NOT, ID, AM) are never flagged', find(await rep(idV), 'acronym-not-spelled-out').filter(i => ['OK', 'NOT', 'ID', 'AM'].includes(i.detail)).length === 0)
    await edit(idV, vh.id, { body: 'Call the API. The APIs return data.' })
    check('a plural ("APIs") counts as the same acronym', find(await rep(idV), 'acronym-not-spelled-out').filter(i => i.detail === 'API').length === 1)
    await edit(idV, vh.id, { body: 'STOP AND READ THIS WHOLE LINE NOW' })
    check('an all-caps line is emphasis, not acronyms', find(await rep(idV), 'acronym-not-spelled-out').filter(i => i.blockId === vh.id).length === 0)
    await edit(idV, vh.id, { body: 'You will use the DNS to look up a name.' })
    const blockers = await (async () => { const { exportBlockers } = require(path.join(REPO, 'backend', 'lessons', 'a11y-check')); const lesson = JSON.parse(fs.readFileSync(lessonFile(idV), 'utf-8')); return exportBlockers(lesson, {}).map(i => i.rule) })()
    check('advisory notes never block an export', !blockers.includes('reading-level') && !blockers.includes('acronym-not-spelled-out'), blockers)

    console.log('Export gate')
    const idE = await draft()
    const le = await lessonOf(idE); const ec = le.blocks.filter(b => b.kind === 'chunk')
    await edit(idE, ec[0].id, { title: ec[0].title, body: ec[0].body, visual: 'v' })
    const blockersAt = lid => {
      const { buildReport, exportBlockers } = require(path.join(REPO, 'backend', 'lessons', 'a11y-check'))
      const lesson = JSON.parse(fs.readFileSync(lessonFile(lid), 'utf-8'))
      return exportBlockers(lesson, {}).map(i => i.rule)
    }
    check('open ERRORS are export blockers', JSON.stringify(blockersAt(idE)) === '["missing-alt-text"]', blockersAt(idE))
    await api('PUT', `${L}/${idE}/a11y/reviews`, { key: find(await rep(idE), 'missing-alt-text')[0].key, reason: 'Reviewed with the accessibility lead' })
    check('a reviewed error no longer blocks', blockersAt(idE).length === 0)
    await edit(idE, ec[1].id, { title: ec[1].title, body: ec[1].body, visual: 'v', decorative: true })
    check('warnings and notes never block an export', blockersAt(idE).length === 0 && find(await rep(idE), 'decorative-no-reason').length === 1)

  } finally {
    await h.stopEnv()
  }
  h.finish()
}
main().catch(e => { console.error(e); process.exit(1) })
